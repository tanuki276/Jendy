create table if not exists public.jendy_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  learning_direction text not null default 'ja-id' check (learning_direction in ('ja-id','id-ja')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.jendy_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_id text not null,
  direction text not null check (direction in ('ja-id','id-ja')),
  score integer check (score is null or (score between 0 and 100)),
  completed boolean not null default false,
  updated_at timestamptz not null default now(),
  unique (user_id, lesson_id, direction)
);

alter table public.jendy_profiles enable row level security;
alter table public.jendy_progress enable row level security;

grant select, insert, update on public.jendy_profiles to authenticated;
grant select, insert, update, delete on public.jendy_progress to authenticated;
grant usage, select on sequence public.jendy_progress_id_seq to authenticated;

create policy "jendy_profiles_select_own" on public.jendy_profiles
for select to authenticated using ((select auth.uid()) = user_id);
create policy "jendy_profiles_insert_own" on public.jendy_profiles
for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "jendy_profiles_update_own" on public.jendy_profiles
for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

create policy "jendy_progress_select_own" on public.jendy_progress
for select to authenticated using ((select auth.uid()) = user_id);
create policy "jendy_progress_insert_own" on public.jendy_progress
for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "jendy_progress_update_own" on public.jendy_progress
for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "jendy_progress_delete_own" on public.jendy_progress
for delete to authenticated using ((select auth.uid()) = user_id);
